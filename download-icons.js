// 去重
const seen = new Set();
const unique = HEROES.filter(([id]) => {
  if (seen.has(id)) return false;
  seen.add(id);
  return true;
}).map(([id, name]) => ({ id, name }));

console.log('Unique heroes:', unique.length);

// 下载图标
const ICON_BASE = 'https://communitydragon.buguoguo.cn/pbe/plugins/rcp-be-lol-game-data/global/default/v1/champion-icons';
const outDir = 'public/icons';

if (!fs.existsSync(outDir)) fs.mkdirSync(outDir, { recursive: true });

let downloaded = 0, failed = 0;

async function downloadAll(){
  for (const hero of unique){
    const file = `${outDir}/${hero.id}.png`;
    if (fs.existsSync(file) && fs.statSync(file).size > 500){ downloaded++; continue; }
    
    await new Promise(resolve => {
      https.get(`${ICON_BASE}/${hero.id}.png`, {headers:{'User-Agent':'Mozilla/5.0'}}, r => {
        if(r.statusCode===200){
          const ws = fs.createWriteStream(file);
          r.pipe(ws);
          r.on('end', ()=>{ws.close(); downloaded++; resolve();});
        }else{ failed++; r.resume(); resolve(); }
      }).on('error', ()=>{failed++; resolve();});
    });
    
    if((downloaded+failed)%50===0) console.log(`Progress: ${downloaded+failed}/${unique.length} ok:${downloaded} fail:${failed}`);
  }
  console.log(`Done! ok:${downloaded} fail:${failed}`);
  
  // 生成数据
  const data = unique.map(h => ({
    id: h.id,
    name: h.name,
    icon: `./public/icons/${h.id}.png`
  }));
  fs.writeFileSync('public/heroes.json', JSON.stringify(data, null, 2));
  console.log('Saved heroes.json with', data.length, 'champions');
}

downloadAll();
